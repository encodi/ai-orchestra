import { ask, expect, test } from './fixtures'

test.describe.configure({ mode: 'serial' })

test('a finished consultation is searchable, replayable from its record, exportable and deletable', async ({ page, open }) => {
  await open()
  await ask(page, 'Pregunta única xylofono para el historial', { strategy: 'thorough' })
  await expect(page.locator('.result')).toBeVisible({ timeout: 60_000 })

  await page.getByRole('link', { name: 'Historial' }).click()
  await expect(page.locator('.hist-item').first()).toBeVisible()
  await page.getByLabel('Buscar').fill('xylofono')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.locator('.hist-item')).toHaveCount(1)
  await page.getByLabel('Buscar').fill('palabra-que-no-existe')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.getByText('No hay consultas que coincidan.')).toBeVisible()
  await page.getByRole('button', { name: 'Limpiar' }).click()

  // Replay: the real recorded messages appear in order, at their recorded times.
  await page.getByLabel('Buscar').fill('xylofono')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.locator('.hist-item')).toHaveCount(1)
  await page.getByRole('link', { name: 'Reproducir' }).click()
  await expect(page.locator('.bubble').first()).toBeVisible()
  const total = await page.locator('.bubble').count()
  expect(total).toBeGreaterThanOrEqual(6)
  await page.getByRole('button', { name: /Reproducir desde el inicio/ }).click()
  await page.getByRole('button', { name: 'Pausar' }).click()
  await page.getByRole('button', { name: 'Reiniciar' }).click()
  await expect(page.locator('.bubble')).toHaveCount(0)
  await page.getByRole('button', { name: 'Siguiente mensaje' }).click()
  await expect(page.locator('.bubble')).toHaveCount(1)
  await page.getByRole('slider', { name: 'Posición de la reproducción' }).focus()
  await page.keyboard.press('End')
  await expect(page.locator('.bubble')).toHaveCount(total)
  await page.getByRole('button', { name: 'Salir de la reproducción' }).click()

  await page.goto(page.url().split('#')[0] + '#/history')
  await page.getByLabel('Buscar').fill('xylofono')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.locator('.hist-item')).toHaveCount(1)
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /Exportar JSON/ }).click()
  expect((await download).suggestedFilename()).toMatch(/^consultation-.*\.json$/)

  await page.getByRole('button', { name: /Eliminar/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar' }).click()
  await expect(page.locator('.hist-item')).toHaveCount(1)
  await page.getByRole('button', { name: /Eliminar/ }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Eliminar' }).click()
  await expect(page.getByText(/Consulta eliminada|Consultation deleted/)).toBeVisible()
  await expect(page.locator('.hist-item')).toHaveCount(0)
})

test('opening a saved consultation shows its answer and can continue its session', async ({ page, open }) => {
  await open()
  await ask(page, 'Pregunta para continuar desde el historial', { strategy: 'fast' })
  await expect(page.locator('.result')).toBeVisible({ timeout: 60_000 })
  const session = await page.locator('.page-head .mono').innerText()
  await page.getByRole('link', { name: 'Historial' }).click()
  await page.getByLabel('Buscar').fill('continuar desde el historial')
  await page.getByRole('button', { name: 'Aplicar' }).click()
  await expect(page.locator('.hist-item')).toHaveCount(1)
  await page.getByRole('link', { name: 'Abrir' }).click()
  await expect(page.getByText('Pregunta para continuar desde el historial').first()).toBeVisible()
  await expect(page.locator('.result table')).toBeVisible()
  await page.getByRole('button', { name: 'Continuar la sesión' }).click()
  await expect(page.locator('.page-head .mono')).toHaveText(session)
})
